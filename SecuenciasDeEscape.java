class SecuenciasDeEscape {
    public static void main(String[] args) {
        System.out.println("Texto 1\nTexto 2");          // Salto de línea
        System.out.println("Texto 3\tTexto 4");          // Tabulación
        System.out.println("Texto 5\rTexto 6");          // Retorno de carro
        System.out.println("\"Texto 7\" Texto 8");       // Comillas dentro del texto
        System.out.println("Texto 9\\ Texto 10");        // Barra invertida
    } // Fin del método main
} // Fin de la clase SecuenciasDeEscape